package ru.nsu.vserova.task112;

/**
 * Достоинство игральной карты.
 *
 * <p>Содержит 13 достоинств от двойки до туза.</p>
 */
public enum Rank {

    /** Двойка (2 очка). */
    Two("Двойка", 2),

    /** Тройка (3 очка). */
    Three("Тройка", 3),

    /** Четвёрка (4 очка). */
    Four("Четвёрка", 4),

    /** Пятёрка (5 очков). */
    Five("Пятёрка", 5),

    /** Шестёрка (6 очков). */
    Six("Шестёрка", 6),

    /** Семёрка (7 очков). */
    Seven("Семёрка", 7),

    /** Восьмёрка (8 очков). */
    Eight("Восьмёрка", 8),

    /** Девятка (9 очков). */
    Nine("Девятка", 9),

    /** Десятка (10 очков). */
    Ten("Десятка", 10),

    /** Валет (10 очков). */
    Jack("Валет", 10),

    /** Дама (10 очков). */
    Queen("Дама", 10),

    /** Король (10 очков). */
    King("Король", 10),

    /** Туз (1/11 очков). */
    Ace("Туз", 11);

    /** Русское название достоинства. */
    private final String russianName;

    /** Значение очков. */
    private final int value;

    /**
     * Создаёт достоинство.
     *
     * @param russianName русское название
     * @param value значение очков
     */
    Rank(String russianName, int value) {
        this.russianName = russianName;
        this.value = value;
    }

    /**
     * Возвращает русское название.
     *
     * @return русское название
     */
    public String getRussianName() {
        return russianName;
    }

    /**
     * Возвращает значение очков.
     *
     * @return значение очков
     */
    public int getValue() {
        return value;
    }
}
